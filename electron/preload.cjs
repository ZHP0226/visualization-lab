const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('workbench', {
  usageStatistics:()=>ipcRenderer.invoke('usage:status'),
  setUsageStatisticsConsent:value=>ipcRenderer.invoke('usage:consent',value),
  recordUsageActivity:()=>ipcRenderer.invoke('usage:activity'),
  aiConfig:()=>ipcRenderer.invoke('ai:config'),
  saveAPIConnection:input=>ipcRenderer.invoke('ai:save-api',input),
  saveLocalConnection:input=>ipcRenderer.invoke('ai:save-local',input),
  removeAIConnection:id=>ipcRenderer.invoke('ai:remove',id),
  testAPIConnection:input=>ipcRenderer.invoke('ai:test-api',input),
  chooseAIProgram:()=>ipcRenderer.invoke('ai:choose-program'),
  sidebarInfo: (id,assetId) => ipcRenderer.invoke('sidebar:info',id,assetId),
  renameSidebarItem: (id,assetId,name) => ipcRenderer.invoke('sidebar:rename',id,assetId,name),
  trashSidebarItem: (id,assetId) => ipcRenderer.invoke('sidebar:trash',id,assetId),
  detachSidebarItem: (id,assetId) => ipcRenderer.invoke('sidebar:detach',id,assetId),
  revealSidebarItem: (id,assetId) => ipcRenderer.invoke('sidebar:reveal',id,assetId),
  setStartupActive: active => ipcRenderer.invoke('startup:active',active),
  initial: () => ipcRenderer.invoke('library:initial'),
  listEditNotes: (project, agent) => ipcRenderer.invoke('notes:list', project, agent),
  saveEditNote: (project, agent, value) => ipcRenderer.invoke('notes:save', project, agent, value),
  removeEditNote: (project, agent, id) => ipcRenderer.invoke('notes:remove', project, agent, id),
  openFolder: () => ipcRenderer.invoke('library:folder'),
  openFile: () => ipcRenderer.invoke('library:file'),
  dropFile: file => ipcRenderer.invoke('library:drop', webUtils.getPathForFile(file)),
  list: (id, relative) => ipcRenderer.invoke('library:list', id, relative),
  model: (id, relative) => ipcRenderer.invoke('library:model', id, relative),
  chooseProjectParent: () => ipcRenderer.invoke('project:parent'),
  createProject: (name, parent) => ipcRenderer.invoke('project:create', name, parent),
  openProject: () => ipcRenderer.invoke('project:open'),
  activateProject: id => ipcRenderer.invoke('project:activate', id),
  refreshProject: id => ipcRenderer.invoke('project:refresh', id),
  projectModel: (id, assetId) => ipcRenderer.invoke('project:model', id, assetId),
  listProjects: () => ipcRenderer.invoke('project:list'),
  projectRender: (id, renderId, expectedHash) => ipcRenderer.invoke('project:render', id, renderId, expectedHash),
  importProjectFiles: (id, kind, modelId) => ipcRenderer.invoke('project:import', id, kind, modelId),
  dropProjectFiles: (id, files) => ipcRenderer.invoke('project:drop', id, Array.from(files, file => webUtils.getPathForFile(file))),
  bindProjectFiles: (id, modelId, renderId, referenceIds) => ipcRenderer.invoke('project:bind', id, modelId, renderId, referenceIds),
  listAgents: () => ipcRenderer.invoke('agent:list'),
  creationOptions: () => ipcRenderer.invoke('creation:options'),
  listChats: (project,agent) => ipcRenderer.invoke('chat:list', project,agent),
  openChat: (project,agent,id) => ipcRenderer.invoke('chat:open', project,agent,id),
  createChat: (project,agent) => ipcRenderer.invoke('chat:create', project,agent),
  saveChatDraft: (id,text) => ipcRenderer.invoke('chat:draft', id,text),
  flushChatDraft: (id,text) => ipcRenderer.sendSync('chat:flush-draft', id,text),
  setAgentPreferences: (id, preference) => ipcRenderer.invoke('agent:preferences', id, preference),
  configureAgentModel: (model, context) => ipcRenderer.invoke('agent:model-options', model, context),
  connectCodex: id => ipcRenderer.invoke('codex:connect', id),
  sendCodex: (text, id, options) => ipcRenderer.invoke('codex:send', text, id, options),
  stopCodex: () => ipcRenderer.invoke('codex:stop'),
  onCodexEvent: listener => {
    const handler = (_event, value) => listener(value);
    ipcRenderer.on('codex:event', handler);
    return () => ipcRenderer.removeListener('codex:event', handler);
  },
  windowAction: action => ipcRenderer.invoke('window:action', action)
});
